from typing import Optional, List
from fastapi import APIRouter, HTTPException, Query, status
from pydantic import BaseModel
from config import get_db_connection

router = APIRouter(prefix="/api", tags=["Alerts, Tracing & Mule Signals"])

class MuleSignalRequest(BaseModel):
    account_ids: List[int]

@router.get("/alerts")
def list_alerts(
    status_filter: Optional[str] = Query(None, alias="status"),
    rule_code: Optional[str] = Query(None),
    min_risk: float = Query(0.0, ge=0.0, le=100.0),
    limit: int = Query(50, ge=1, le=500),
    offset: int = Query(0, ge=0)
):
    """Fetch fraud detection alerts generated by SQL detection rules."""
    query = """
        SELECT a.alert_id, a.txn_id, a.account_id, a.rule_code, a.risk_score,
               a.explanation, a.evidence_query, a.status, a.created_at,
               t.from_account, t.to_account, t.amount, t.txn_type
        FROM alerts a
        LEFT JOIN transactions t ON a.txn_id = t.txn_id
        WHERE a.risk_score >= %s
    """
    params = [min_risk]

    if status_filter:
        query += " AND a.status = %s"
        params.append(status_filter)
    if rule_code:
        query += " AND a.rule_code = %s"
        params.append(rule_code)

    query += " ORDER BY a.risk_score DESC, a.alert_id DESC LIMIT %s OFFSET %s;"
    params.extend([limit, offset])

    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(query, params)
            return cur.fetchall()

@router.get("/alerts/{alert_id}")
def get_alert(alert_id: int):
    """Get single alert details with full JSON explanation and SQL evidence query."""
    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT a.alert_id, a.txn_id, a.account_id, a.rule_code, a.risk_score,
                       a.explanation, a.evidence_query, a.status, a.created_at,
                       t.from_account, t.to_account, t.amount
                FROM alerts a
                LEFT JOIN transactions t ON a.txn_id = t.txn_id
                WHERE a.alert_id = %s;
                """,
                (alert_id,)
            )
            row = cur.fetchone()
            if not row:
                raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"Alert {alert_id} not found")
            return row

@router.post("/alerts/sweep")
def trigger_detection_sweep():
    """Triggers in-database full anomaly sweep procedure sp_run_detection_sweep()."""
    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute("SELECT sp_run_detection_sweep() AS alerts_created;")
            res = cur.fetchone()
            conn.commit()
            return {"status": "SUCCESS", "new_alerts_created": res["alerts_created"]}

@router.get("/trace/{root_txn_id}")
def trace_money_trail(
    root_txn_id: int,
    hours: int = Query(48, ge=1, le=168, description="Time window in hours"),
    max_hops: int = Query(6, ge=1, le=10, description="Maximum traversal hop depth")
):
    """
    Executes PostgreSQL WITH RECURSIVE fn_trace_stolen_money to follow stolen funds forward
    in time across bounded hops with haircut attribution. Returns formatted nodes and edges for Cytoscape.js.
    """
    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT hop_depth, parent_txn_id, txn_id, from_account, to_account,
                       txn_amount, attributed_amount, created_at, path_accounts, path_txns, is_cycle
                FROM fn_trace_stolen_money(
                    %s::bigint,
                    (%s || ' hours')::interval,
                    %s::int
                );
                """,
                (root_txn_id, hours, max_hops)
            )
            rows = cur.fetchall()

            if not rows:
                raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail=f"No transaction found for root_txn_id {root_txn_id}")

            # Assemble Cytoscape graph structure
            nodes = {}
            edges = []
            visited_accounts = set()

            for r in rows:
                from_id = str(r["from_account"])
                to_id = str(r["to_account"])

                visited_accounts.add(r["from_account"])
                visited_accounts.add(r["to_account"])

                if from_id not in nodes:
                    nodes[from_id] = {
                        "id": f"acc_{from_id}",
                        "label": f"Account #{from_id}",
                        "account_id": r["from_account"],
                        "hop": r["hop_depth"] - 1,
                        "type": "VICTIM" if r["hop_depth"] == 1 else "INTERMEDIARY"
                    }
                if to_id not in nodes:
                    nodes[to_id] = {
                        "id": f"acc_{to_id}",
                        "label": f"Account #{to_id}",
                        "account_id": r["to_account"],
                        "hop": r["hop_depth"],
                        "type": "DESTINATION"
                    }

                edges.append({
                    "id": f"edge_{r['txn_id']}",
                    "source": f"acc_{from_id}",
                    "target": f"acc_{to_id}",
                    "txn_id": r["txn_id"],
                    "hop_depth": r["hop_depth"],
                    "txn_amount": float(r["txn_amount"]),
                    "attributed_amount": float(r["attributed_amount"]),
                    "created_at": r["created_at"].isoformat() if hasattr(r["created_at"], "isoformat") else str(r["created_at"]),
                    "is_cycle": r["is_cycle"]
                })

            return {
                "root_txn_id": root_txn_id,
                "traversal_summary": {
                    "total_hops": max(r["hop_depth"] for r in rows),
                    "total_transfers": len(rows),
                    "unique_accounts": len(visited_accounts)
                },
                "graph": {
                    "nodes": list(nodes.values()),
                    "edges": edges
                },
                "raw_trail": rows
            }

@router.post("/mule-signals")
def get_mule_network_signals(req: MuleSignalRequest):
    """
    Executes fn_get_mule_network_signals() to discover shared devices, phone numbers,
    and IP addresses connecting a group of investigated accounts.
    """
    if not req.account_ids:
        return {"signals": []}

    with get_db_connection() as conn:
        with conn.cursor() as cur:
            cur.execute(
                """
                SELECT source_account, target_account, signal_type, shared_identifier, details, classification
                FROM fn_get_mule_network_signals(%s::bigint[]);
                """,
                (req.account_ids,)
            )
            signals = cur.fetchall()
            return {"count": len(signals), "signals": signals}
